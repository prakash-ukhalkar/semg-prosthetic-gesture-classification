def load_subject_exercise(subject_id: int, exercise_id: int, raw_dir: Path) -> Optional[Dict[str, np.ndarray]]:
    """
    Load the MATLAB data file for a specific subject and exercise subset.

    Parameters
    ----------
    subject_id : int
        The subject ID (1 to 40).
    exercise_id : int
        The exercise ID (1 to 3).
    raw_dir : Path
        The Path to the raw data directory.

    Returns
    -------
    Optional[Dict[str, np.ndarray]]
        A dictionary containing sEMG and kinemetic data arrays, or None if the
        file does not exist or fails to load.
    """
    file_path = raw_dir / f'DB2_s{subject_id}' / f'S{subject_id}_E{exercise_id}_A1.mat'
    if not file_path.exists():
        return None
    try:
        mat_data = scipy.io.loadmat(str(file_path))
        # Remove metadata keys and keep arrays
        cleaned_data = {
            k: v for k, v in mat_data.items()
            if not k.startswith('__')
        }
        return cleaned_data
    except Exception as e:
        import logging
        logging.getLogger('semg_prosthetic_classification').error(
            f'Failed to load {file_path.name}: {e}'
        )
        return None
